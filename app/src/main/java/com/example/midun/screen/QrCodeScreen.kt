@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun QrCodeScreen(
    onBack: () -> Unit,
    onScanConnected: () -> Unit = onBack,
    chatViewModel: ChatViewModel = hiltViewModel()
) {
    var selectedTab by remember { mutableIntStateOf(0) } // 0=生成 1=识别
    var isGenerating by remember { mutableStateOf(false) }
    var qrGenerated by remember { mutableStateOf(false) }
    var countdown by remember { mutableIntStateOf(120) }
    var qrBitmap by remember { mutableStateOf<Bitmap?>(null) }
    var qrContent by remember { mutableStateOf<String?>(null) }
    var qrError by remember { mutableStateOf<String?>(null) }
    // 出码侧网络诊断（真机排障）：生成时采集本机 IPv6，直观暴露「本机有没有公网 IPv6」。
    var diag by remember { mutableStateOf<P2PSessionManager.NetworkDiagnostics?>(null) }

    // 扫码状态（patch §M6 改动4）
    var scanned by remember { mutableStateOf(false) }
    var scannedContent by remember { mutableStateOf("") }
    var showRemarkDialog by remember { mutableStateOf(false) }

    // 真实连接状态（M10.3）：源自 P2PSessionManager 单例，A 出码后显示等待/已连接。
    val connectionState by chatViewModel.connectionState.collectAsStateWithLifecycle()

    // 离开本屏时：若未建立连接，停止监听释放 ServerSocket；已连接则保留会话供后续聊天（M10.4）。
    DisposableEffect(Unit) {
        onDispose {
            if (chatViewModel.connectionState.value != ConnectionState.CONNECTED) {
                chatViewModel.stopConnection()
            }
        }
    }

    LaunchedEffect(qrGenerated) {
        if (qrGenerated) {
            while (countdown > 0) {
                delay(1000)
                countdown--
            }
            // 过期：清状态与图像，回到 pre-gen，下次需重新点按钮渲染。未连上则一并停监听。
            qrGenerated = false
            countdown = 120
            qrBitmap = null
            qrContent = null
            if (chatViewModel.connectionState.value != ConnectionState.CONNECTED) {
                chatViewModel.stopConnection()
            }
        }
    }

    // 渲染 LaunchedEffect 提到顶层（脱离 pre-gen 分支），让 post-gen 的"重新生成"
    // 也能复用同一渲染路径——原地刷新 bitmap/content + 重置倒计时，不退回 pre-gen 卡片。
    LaunchedEffect(isGenerating) {
        if (isGenerating) {
            // M10.3：生成真实 ConnectionInfo（含本机 IPv6 + 临时 ECDH 公钥）并后台开始监听对端连入。
            val content = chatViewModel.prepareConnection()
            diag = chatViewModel.networkDiagnostics() // 采集本机 IPv6 诊断（与二维码同一地址）
            val bitmap = runCatching {
                withContext(Dispatchers.Default) {
                    val pngBytes = QRCode.ofSquares()
                        .withSize(10)
                        .build(content)
                        .render()
                        .getBytes()
                    BitmapFactory.decodeByteArray(pngBytes, 0, pngBytes.size)
                }
            }.getOrNull()
            if (bitmap != null) {
                qrBitmap = bitmap
                qrContent = content
                countdown = 120
                qrGenerated = true
            } else {
                qrError = "二维码生成失败，请重试"
            }
            isGenerating = false
        }
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("扫码建链") },
                navigationIcon = {
                    IconButton(onClick = onBack) { Icon(Icons.Default.ArrowBack, "返回") }
                },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = Primary, titleContentColor = Color.White,
                    navigationIconContentColor = Color.White
                )
            )
        }
    ) { padding ->
        Column(
            modifier = Modifier.fillMaxSize().padding(padding).padding(24.dp),
            horizontalAlignment = Alignment.CenterHorizontally
        ) {
            // Tab切换
            TabRow(
                selectedTabIndex = selectedTab,
                containerColor = Surface,
                modifier = Modifier.clip(RoundedCornerShape(12.dp))
            ) {
                Tab(selected = selectedTab == 0, onClick = { selectedTab = 0 }) {
                    Row(Modifier.padding(12.dp), verticalAlignment = Alignment.CenterVertically) {
                        Icon(Icons.Default.QrCode, null, modifier = Modifier.size(18.dp))
                        Spacer(Modifier.width(4.dp))
                        Text("生成二维码")
                    }
                }
                Tab(selected = selectedTab == 1, onClick = { selectedTab = 1 }) {
                    Row(Modifier.padding(12.dp), verticalAlignment = Alignment.CenterVertically) {
                        Icon(Icons.Default.QrCodeScanner, null, modifier = Modifier.size(18.dp))
                        Spacer(Modifier.width(4.dp))
                        Text("识别二维码")
                    }
                }
            }

            Spacer(Modifier.height(16.dp))

            if (selectedTab == 0) {
                // 生成二维码
                if (!qrGenerated) {
                    Card(
                        modifier = Modifier.fillMaxWidth(),
                        shape = RoundedCornerShape(16.dp),
                        colors = CardDefaults.cardColors(containerColor = Surface)
                    ) {
                        Column(Modifier.padding(20.dp)) {
                            Text("连接信息", fontWeight = FontWeight.Bold)
                            Spacer(Modifier.height(12.dp))
                            // M10.3：点生成时实时取真实值（本机 IPv6、随机会话 ID、临时 ECDH 公钥），
                            // pre-gen 卡仅说明将包含哪些字段。
                            InfoRow("设备SN", "本机安全卡")
                            InfoRow("IPv6地址", "生成时获取本机地址")
                            InfoRow("会话ID", "随机生成")
                            InfoRow("临时公钥", "P-256 临时 ECDH 公钥")
                            InfoRow("有效期", "120秒")
                        }
                    }

                    Spacer(Modifier.height(24.dp))

                    Button(
                        onClick = {
                            qrError = null
                            isGenerating = true
                        },
                        enabled = !isGenerating,
                        modifier = Modifier.fillMaxWidth().height(48.dp),
                        shape = RoundedCornerShape(12.dp),
                        colors = ButtonDefaults.buttonColors(containerColor = Primary)
                    ) {
                        if (isGenerating) {
                            CircularProgressIndicator(color = Color.White, strokeWidth = 2.dp, modifier = Modifier.size(20.dp))
                        } else {
                            Icon(Icons.Default.QrCode, null)
                            Spacer(Modifier.width(8.dp))
                            Text("生成临时ECDH密钥对并创建二维码")
                        }
                    }

                    qrError?.let {
                        Spacer(Modifier.height(12.dp))
                        Text(it, color = Danger, fontSize = 13.sp, textAlign = TextAlign.Center)
                    }
                } else {
                    // 显示二维码
                    Box(
                        modifier = Modifier
                            .size(220.dp)
                            .clip(RoundedCornerShape(16.dp))
                            .background(Color.White)
                            .border(2.dp, Primary, RoundedCornerShape(16.dp)),
                        contentAlignment = Alignment.Center
                    ) {
                        qrBitmap?.let { bmp ->
                            Image(
                                bitmap = bmp.asImageBitmap(),
                                contentDescription = "连接二维码",
                                modifier = Modifier.size(200.dp)
                            )
                        }
                    }

                    Spacer(Modifier.height(16.dp))

                    // 倒计时
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Icon(Icons.Default.Timer, null, tint = if (countdown < 30) Danger else Accent, modifier = Modifier.size(18.dp))
                        Spacer(Modifier.width(4.dp))
                        Text(
                            "有效期：${countdown}秒",
                            color = if (countdown < 30) Danger else Accent,
                            fontWeight = FontWeight.Medium
                        )
                    }

                    Spacer(Modifier.height(8.dp))
                    qrContent?.let {
                        Text(
                            it,
                            fontSize = 10.sp,
                            color = TextSecondary,
                            textAlign = TextAlign.Center
                        )
                    }

                    // 本机出站地址诊断（真机排障）：二维码里写的就是这个地址。无可用直连地址时
                    // 对端必然「网络不可达」，红字直接点出根因；WiFi 局域网/公网 IPv6 时绿字给出地址。
                    diag?.let { d ->
                        Spacer(Modifier.height(12.dp))
                        val noRoute = d.selectedAddress == "::1"
                        Card(
                            modifier = Modifier.fillMaxWidth(),
                            shape = RoundedCornerShape(12.dp),
                            colors = CardDefaults.cardColors(
                                containerColor = (if (noRoute) Danger else Success).copy(alpha = 0.10f)
                            )
                        ) {
                            Column(Modifier.padding(12.dp)) {
                                Text(
                                    "本机出站地址：${d.selectedAddress}",
                                    fontSize = 12.sp,
                                    fontWeight = FontWeight.Medium,
                                    color = if (noRoute) Danger else Success
                                )
                                Spacer(Modifier.height(4.dp))
                                Text(
                                    if (noRoute) {
                                        "本机无可用直连地址 → 对方扫码必报「网络不可达」。请连 WiFi，或改用移动数据。"
                                    } else {
                                        "路径：${d.kind}。两台手机连同一 WiFi 时走局域网直连最稳。"
                                    },
                                    fontSize = 11.sp,
                                    color = TextSecondary
                                )
                                if (d.allAddresses.isNotEmpty()) {
                                    Spacer(Modifier.height(6.dp))
                                    Text(
                                        "全部地址：${d.allAddresses.joinToString("  ")}",
                                        fontSize = 9.sp,
                                        color = TextSecondary
                                    )
                                }
                            }
                        }
                    }

                    Spacer(Modifier.height(16.dp))

                    // 真实连接状态（M10.3）：等待对端扫码连入 → 已建立加密连接
                    when (connectionState) {
                        ConnectionState.CONNECTED -> Row(verticalAlignment = Alignment.CenterVertically) {
                            Icon(Icons.Default.CheckCircle, null, tint = Success, modifier = Modifier.size(18.dp))
                            Spacer(Modifier.width(6.dp))
                            Text("已建立加密连接", color = Success, fontWeight = FontWeight.Medium)
                        }
                        ConnectionState.LISTENING -> Row(verticalAlignment = Alignment.CenterVertically) {
                            CircularProgressIndicator(strokeWidth = 2.dp, modifier = Modifier.size(16.dp), color = Primary)
                            Spacer(Modifier.width(8.dp))
                            Text("等待对方扫码连接…", color = TextSecondary, fontSize = 13.sp)
                        }
                        else -> {}
                    }

                    Spacer(Modifier.height(20.dp))

                    OutlinedButton(
                        onClick = {},
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Icon(Icons.Default.Share, null)
                        Spacer(Modifier.width(8.dp))
                        Text("分享")
                    }

                    Spacer(Modifier.height(8.dp))

                    // 原地刷新：触发顶层渲染 LaunchedEffect 重渲一张并重置倒计时，不退回 pre-gen 卡片。
                    TextButton(
                        onClick = {
                            qrError = null
                            isGenerating = true
                        },
                        enabled = !isGenerating
                    ) {
                        if (isGenerating) {
                            CircularProgressIndicator(
                                strokeWidth = 2.dp,
                                modifier = Modifier.size(16.dp)
                            )
                            Spacer(Modifier.width(8.dp))
                            Text("刷新中…")
                        } else {
                            Text("重新生成")
                        }
                    }

                    qrError?.let {
                        Spacer(Modifier.height(8.dp))
                        Text(it, color = Danger, fontSize = 13.sp, textAlign = TextAlign.Center)
                    }
                }
            } else {
                ScanTab(
                    scanned = scanned,
                    onQrDetected = { value ->
                        scanned = true
                        scannedContent = value
                        showRemarkDialog = true
                    }
                )
            }
        }
    }

    if (showRemarkDialog) {
        var remark by remember { mutableStateOf("") }
        var connecting by remember { mutableStateOf(false) }
        var connectError by remember { mutableStateOf<String?>(null) }
        AlertDialog(
            // 强制填备注：点外部 / 返回键不关闭弹框（按用户决策，仍提供"取消"按钮逃生口）。
            // 连接进行中也禁止点外部关闭。
            onDismissRequest = { /* no-op：禁止点外部关闭 */ },
            icon = { Icon(Icons.Default.PersonAdd, null, tint = Primary) },
            title = { Text("为联系人添加备注") },
            text = {
                Column {
                    Text(
                        "连接码：${scannedContent.take(40)}${if (scannedContent.length > 40) "..." else ""}",
                        color = TextSecondary,
                        fontSize = 12.sp
                    )
                    Spacer(Modifier.height(12.dp))
                    OutlinedTextField(
                        value = remark,
                        onValueChange = { remark = it },
                        label = { Text("备注名称（如：张三）") },
                        singleLine = true,
                        enabled = !connecting,
                        modifier = Modifier.fillMaxWidth()
                    )
                    connectError?.let {
                        Spacer(Modifier.height(8.dp))
                        Text(it, color = Danger, fontSize = 12.sp)
                    }
                }
            },
            confirmButton = {
                Button(
                    onClick = {
                        // M10.3：先真实 connectTo + ECDH 握手，成功才建联系人并返回。
                        connecting = true
                        connectError = null
                        chatViewModel.connectToContact(
                            qrContent = scannedContent,
                            remark = remark.trim(),
                            onConnected = {
                                connecting = false
                                showRemarkDialog = false
                                scanned = false
                                scannedContent = ""
                                onScanConnected()
                            },
                            onError = { msg ->
                                connecting = false
                                connectError = msg
                            }
                        )
                    },
                    enabled = remark.isNotBlank() && !connecting,
                    colors = ButtonDefaults.buttonColors(containerColor = Primary)
                ) {
                    if (connecting) {
                        CircularProgressIndicator(color = Color.White, strokeWidth = 2.dp, modifier = Modifier.size(18.dp))
                        Spacer(Modifier.width(8.dp))
                        Text("连接中…")
                    } else {
                        Text("确认建链")
                    }
                }
            },
            dismissButton = {
                // 偏离 patch：patch 无取消按钮（强制填写），实测对误扫无逃生口。连接中禁用。
                TextButton(
                    onClick = {
                        chatViewModel.stopConnection() // 放弃本次连接尝试
                        showRemarkDialog = false
                        scanned = false        // 允许重扫
                        scannedContent = ""
                    },
                    enabled = !connecting
                ) { Text("取消", color = TextSecondary) }
            }
        )
    }
}

@Composable
private fun ScanTab(
    scanned: Boolean,
    onQrDetected: (String) -> Unit
) {
    val context = LocalContext.current
    var hasCameraPermission by remember {
        mutableStateOf(
            ContextCompat.checkSelfPermission(
                context, Manifest.permission.CAMERA
            ) == PackageManager.PERMISSION_GRANTED
        )
    }
    val permissionLauncher = rememberLauncherForActivityResult(
        contract = ActivityResultContracts.RequestPermission()
    ) { granted -> hasCameraPermission = granted }

    // 首次进入识别 Tab、未授权 → 自动弹一次系统权限框。被拒后改为手动点按钮重试。
    LaunchedEffect(Unit) {
        if (!hasCameraPermission) {
            permissionLauncher.launch(Manifest.permission.CAMERA)
        }
    }

    Box(
        modifier = Modifier
            .fillMaxWidth()
            .height(300.dp)
            .clip(RoundedCornerShape(16.dp))
            .background(PrimaryDark)
            .border(2.dp, Primary, RoundedCornerShape(16.dp)),
        contentAlignment = Alignment.Center
    ) {
        if (hasCameraPermission) {
            CameraPreview(scanned = scanned, onQrDetected = onQrDetected)
        } else {
            Column(horizontalAlignment = Alignment.CenterHorizontally) {
                Icon(
                    Icons.Default.CameraAlt,
                    null,
                    tint = Color.White.copy(0.5f),
                    modifier = Modifier.size(64.dp)
                )
                Spacer(Modifier.height(12.dp))
                Text("需要相机权限以扫描二维码", color = Color.White.copy(0.8f), fontSize = 13.sp)
                Spacer(Modifier.height(12.dp))
                Button(
                    onClick = { permissionLauncher.launch(Manifest.permission.CAMERA) },
                    colors = ButtonDefaults.buttonColors(containerColor = Accent)
                ) {
                    Text("授权相机")
                }
            }
        }
    }

    Spacer(Modifier.height(16.dp))

    // M0 占位：相册选图扫码非 patch 规定，留待后续实现（与 M6.7 "分享" 同样保留）。
    OutlinedButton(
        onClick = {},
        modifier = Modifier.fillMaxWidth()
    ) {
        Icon(Icons.Default.Image, null)
        Spacer(Modifier.width(8.dp))
        Text("从手机相册选择二维码图片")
    }

    Spacer(Modifier.height(16.dp))

    Card(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(12.dp),
        colors = CardDefaults.cardColors(containerColor = Surface)
    ) {
        Row(Modifier.padding(12.dp), verticalAlignment = Alignment.CenterVertically) {
            Icon(Icons.Default.Info, null, tint = Primary, modifier = Modifier.size(18.dp))
            Spacer(Modifier.width(8.dp))
            Text(
                "识别成功后将验证来源、IPv6地址及签名，确认后建立加密连接",
                fontSize = 12.sp,
                color = TextSecondary
            )
        }
    }
}

@Composable
private fun CameraPreview(
    scanned: Boolean,
    onQrDetected: (String) -> Unit
) {
    val context = LocalContext.current
    val lifecycleOwner = LocalLifecycleOwner.current
    // 读取最新的 scanned 闭包值：analyzer 注册一次但每帧都读这个 state。
    val scannedState = rememberUpdatedState(scanned)
    val onQrDetectedState = rememberUpdatedState(onQrDetected)

    val barcodeScanner = remember {
        BarcodeScanning.getClient(
            BarcodeScannerOptions.Builder()
                .setBarcodeFormats(Barcode.FORMAT_QR_CODE)
                .build()
        )
    }

    // 离开识别 Tab / 屏幕销毁时显式 unbind 相机并关闭 scanner。
    // CameraX 虽绑定到 Activity lifecycle，但 Tab 切回生成后 AndroidView 离场，
    // 相机会继续占用传感器、analyzer 持续解码——主动释放避免泄漏。
    DisposableEffect(Unit) {
        onDispose {
            runCatching { ProcessCameraProvider.getInstance(context).get().unbindAll() }
            runCatching { barcodeScanner.close() }
        }
    }

    AndroidView(
        factory = { ctx ->
            val previewView = PreviewView(ctx)
            val cameraProviderFuture = ProcessCameraProvider.getInstance(ctx)
            cameraProviderFuture.addListener({
                val cameraProvider = cameraProviderFuture.get()
                val preview = Preview.Builder().build().also {
                    it.setSurfaceProvider(previewView.surfaceProvider)
                }
                val imageAnalyzer = ImageAnalysis.Builder()
                    .setBackpressureStrategy(ImageAnalysis.STRATEGY_KEEP_ONLY_LATEST)
                    .build()
                    .also { analysis ->
                        analysis.setAnalyzer(ContextCompat.getMainExecutor(ctx)) { imageProxy ->
                            if (scannedState.value) {
                                imageProxy.close()
                                return@setAnalyzer
                            }
                            val mediaImage = imageProxy.image
                            if (mediaImage != null) {
                                val image = InputImage.fromMediaImage(
                                    mediaImage,
                                    imageProxy.imageInfo.rotationDegrees
                                )
                                barcodeScanner.process(image)
                                    .addOnSuccessListener { barcodes ->
                                        barcodes.firstOrNull()?.rawValue?.let { raw ->
                                            if (!scannedState.value) {
                                                onQrDetectedState.value(raw)
                                            }
                                        }
                                    }
                                    .addOnCompleteListener { imageProxy.close() }
                            } else {
                                imageProxy.close()
                            }
                        }
                    }
                runCatching {
                    cameraProvider.unbindAll()
                    cameraProvider.bindToLifecycle(
                        lifecycleOwner,
                        CameraSelector.DEFAULT_BACK_CAMERA,
                        preview,
                        imageAnalyzer
                    )
                }
            }, ContextCompat.getMainExecutor(ctx))
            previewView
        },
        modifier = Modifier.fillMaxSize()
    )
}

@Composable
private fun InfoRow(label: String, value: String) {
    Row(
        modifier = Modifier.fillMaxWidth().padding(vertical = 4.dp),
        horizontalArrangement = Arrangement.SpaceBetween
    ) {
        Text(label, fontSize = 13.sp, color = TextSecondary)
        Text(value, fontSize = 13.sp, fontWeight = FontWeight.Medium)
    }
}